local Q,test=...
local T,C=Q.Trips,Q.Core
local function state()
    return {map=1438,level=10,pos={x=.2,y=.2},done={},skip={},log={},mode="xp",budget=10,freeSlots=10}
end
local function quest(id,xp,x,y)
    local p={x=x or .6,y=y or .6}
    return {id=id,name="Synthetic quest "..id,level=5,minLevel=1,xp=xp or 100,minutes=3,
        start=p,objective=p,finish=p}
end
local function contains(trip,id)
    for _,q in ipairs(trip.quests) do if q.id==id then return true end end
    return false
end
local function guarded(fn)
    local oldBuild,oldPack=T.Build,Q.Pack
    Q.Pack={mapID=1438,bounds={minX=0,maxX=1,minY=0,maxY=1}}
    local ok,err=pcall(fn)
    T.Build=oldBuild;Q.Pack=oldPack
    assert(ok,err)
end

-- A controlled score valley isolates the search failure without copying any
-- saved quest snapshot: all three-member returns are valid, but no improving
-- two-member insertion reaches the useful prior group. Geometry and precedence
-- are still generated by the real Build; only its ranking inputs are controlled.
local function scoreValley()
    local qs={quest(1001,100,.45,.45),quest(1002,100,.55,.45),quest(1003,100,.65,.45),quest(1004,100,.75,.45)}
    local s=state();for _,q in ipairs(qs) do s.log[q.id]={complete=true} end
    local original=T.Build
    T.Build=function(selected,current)
        local trip=original(selected,current)
        if not trip then return nil end
        local n=#selected
        if n==1 then trip.score=selected[1].id==1004 and 105 or 100
        elseif contains(trip,1004) then trip.score=20
        elseif n==3 then trip.score=98
        else trip.score=95 end
        return trip
    end
    s.previous={tripKey="1001,1002,1003",nextKey="1001:return"}
    return qs,s
end

test("valid previous group survives a greedy score valley across unchanged refreshes",function()
    guarded(function()
        local qs,s=scoreValley()
        for _=1,20 do
            local trip=T.Choose(qs,s)
            assert(trip.key=="1001,1002,1003","valid near-best prior group must not depend on greedy rediscovery")
            assert(trip.steps[1].key=="1001:return","unchanged next action must stay stable")
            s.previous={tripKey=trip.key,nextKey=trip.steps[1].key}
        end
        s.previous=nil
        assert(T.Choose(qs,s).key=="1004","the old group is not independently found by greedy insertion")
    end)
end)

test("previous retention still releases a group that loses beyond the existing margin",function()
    guarded(function()
        local qs,s=scoreValley();local valley=T.Build
        T.Build=function(selected,current)
            local trip=valley(selected,current)
            if trip and trip.key=="1001,1002,1003" then trip.score=80 end
            return trip
        end
        assert(T.Choose(qs,s).key=="1004","stability must not freeze a materially inferior plan")
    end)
end)

test("previous group cannot retain skipped failed completed removed or unlocated members",function()
    guarded(function()
        local realBuild=T.Build
        for _,invalid in ipairs({"skip","failed","done","removed","location"}) do
            T.Build=realBuild
            local qs,s=scoreValley()
            if invalid=="skip" then s.skip[1002]=true
            elseif invalid=="failed" then s.log[1002].failed=true
            elseif invalid=="done" then s.done[1002]=true
            elseif invalid=="removed" then table.remove(qs,2)
            else qs[2].objective=nil;qs[2].finish=nil end
            local trip=T.Choose(qs,s)
            assert(trip and not contains(trip,1002),"stale group must respect current "..invalid.." state")
        end
    end)
end)

test("malformed or oversized previous identities never bypass bounded current planning",function()
    guarded(function()
        local q=quest(1010);local s=state();s.log[q.id]={complete=true}
        for _,key in ipairs({"",",1010","1010,","1010,,1010","1010,1010","x1010","1010;9999",string.rep("1",65),"1010,1011,1012,1013,1014"}) do
            s.previous={tripKey=key,nextKey="1010:return"}
            local trip=T.Choose({q},s)
            assert(trip and trip.key=="1010" and #trip.quests==1)
        end
    end)
end)

test("prior pickup group obeys current capacity and unresolved prerequisite safeguards",function()
    guarded(function()
        local a,b=quest(1020,400,.5,.5),quest(1021,600,.6,.6)
        b.all={a.id};local s=state();s.previous={tripKey="1020,1021",nextKey="1020:pickup"};s.freeSlots=0
        assert(T.Choose({a,b},s)==nil,"old pickups cannot consume unavailable log slots")
        s.freeSlots=10;a.stageOnly=true;a.pendingAction="PICK UP";a.objective=nil;a.finish=nil
        local trip=T.Choose({a,b},s)
        assert(trip and not contains(trip,b.id),"unknown parent stage cannot unlock a retained child")
        a.stageOnly=nil;a.pendingAction=nil;a.objective=a.start;a.finish=a.start
        s.previous={tripKey="1020,1021",nextKey="1020:pickup"}
        trip=T.Choose({a,b},s)
        if contains(trip,b.id) then
            local returned,picked
            for i,step in ipairs(trip.steps) do
                for _,m in ipairs(step.members) do
                    if m.id==a.id and m.action=="TURN IN" then returned=i end
                    if m.id==b.id and m.action=="PICK UP" then picked=i end
                end
            end
            assert(returned and picked and returned<picked,"retained children still wait for parent returns")
        end
    end)
end)

test("urgent nearby-ready and current pin priorities still supersede retained grouping",function()
    guarded(function()
        local qs,s=scoreValley()
        qs[4].timed=true
        assert(T.Choose(qs,s).urgent and T.Choose(qs,s).key=="1004")
        qs[4].timed=nil;s.pos=C.Copy(qs[4].finish)
        local trip=T.Choose(qs,s);assert(trip.nearbyReturns and trip.key=="1004")
        s.pos={x=.2,y=.2};s.pin=1004
        assert(T.Choose(qs,s).key=="1004","new pin wins over a retained group that excludes it")
    end)
end)

test("valid old group is considered independently of the sixteen-candidate shortlist",function()
    guarded(function()
        local qs,s={},state()
        for i=1,20 do
            qs[i]=quest(1100+i,i==20 and 1 or 1000,.4+i*.01,.7)
            s.log[qs[i].id]={complete=true}
        end
        s.previous={tripKey="1120",nextKey="1120:return"}
        local original=T.Build;local oldBuilt=false
        T.Build=function(selected,current)
            local trip=original(selected,current)
            if trip then
                if #selected==1 and selected[1].id==1120 then oldBuilt=true;trip.score=99
                elseif #selected==1 then trip.score=100
                else trip.score=1 end
            end
            return trip
        end
        local trip=T.Choose(qs,s)
        assert(oldBuilt and trip.key=="1120","shortlist cannot hide a still-valid near-best previous singleton")
    end)
end)
